#include <stdio.h>
#include <locale.h>

int main() {

	setlocale(LC_CTYPE, "RUS");

	_Bool* pа, x = 5; // меняем char на long double/short unsigned int/_Bool

	pа = &x;

	printf("По адресу %p хранится *ptr=%g\n", pа, *pа);

	pа++;

	printf("По адресу %p хранится *ptr=%g\n", pа, *pа);

	pа--;

	printf("По адресу %p хранится *ptr=%g\n", pа, *pа);

	return 0;
}

/* Мы создаём переменную x типа int со значением 5, также 
мы создаём указатель pa с типом int. При помощи символа &
мы получаем адрес ячейки, которая выделена под переменную x.
Записываем полученное значение в указатель pa. Далее выводим
адрес ячейки, на которую указывае указатель (то есть, ячейка 
памяти выделенная под переменную x), при помощи спецификатора 
%p. Также выводим значение ячейки памяти при помощи спецификатора
%g (из-за типа int происходит неопределённое поведение) 
и символа * (операции разименования),
на которую указывает указатель pa. Далее мы сдвигаем указатель на 1, 
то есть адресс ячейки смещается на 4 байта (размер типа int). 
Так как мы не указывали значение для переменной рядом, то при
выводе мы увидим неопределённое поведение. При сдвиге обратно
мы снова получаем значение переменной x*/

/* Заменив тип переменной и указателей с int на double мы 
замечаем, что при сдвиге указателя адрес меняется на 8 байт
а не 4*/

/* Заменив тип переменной и указателей с double на char мы
замечаем, что при сдвиге указателя адрес меняется на 1 байт
а не 8*/

