#include <stdio.h>
#include <locale.h>

int main()

{
	setlocale(LC_CTYPE, "RUS");

	float PI = 3.14159, * p1, * p2;

	p1 = p2 = &PI;

	printf("По адресу p1=%p хранится *p1=%g\n", p1, *p1);

	printf("По адресу p2=%p хранится *p2=%g\n", p2, *p2);

}

/* Объяснение кода - мы создаём переменную PI типа float со значением 3.14159, 
а также создаём два указателя p1 и p2 с аналогичным типом. Далее мы приравниваем 
значения, взяв адрес переменной PI благодаря символу &. После этого мы выводим
адрес переменной PI при помощи спецификатора %p и выводим значения, которые храняться 
в этих ячейках при помощи символа *. */